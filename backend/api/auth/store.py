"""Accounts, roles, health records and audit log for the doctor module (SQLite at backend/data/curanex.db, git-ignored).

- Passwords: scrypt with a per-user salt. Login tokens: random, only their SHA-256 is stored, 7-day expiry.
- Roles: patient, doctor (pending -> approved/rejected/suspended by the admin by hand), admin (the email in ADMIN_EMAIL).
- Record contents (symptoms, reports, model results, doctor plans) are encrypted at rest with RECORDS_KEY (Fernet).
- Every read/change of a case is written to the audit log.
Keys live in backend/.env (git-ignored); missing keys are generated there on first use.
"""

import hashlib
import hmac
import json
import os
import secrets
import sqlite3
import threading
import time
from pathlib import Path

from cryptography.fernet import Fernet

BACKEND = Path(__file__).resolve().parents[2]
DB = BACKEND / "data" / "curanex.db"
ENV_FILE = BACKEND / ".env"
TOKEN_TTL_S = 7 * 24 * 3600
_lock = threading.Lock()


def env_value(name: str, generate: bool = False) -> str:
    """Setting from the environment, else backend/.env; optionally generated and saved there once."""
    if os.environ.get(name):
        return os.environ[name]
    if ENV_FILE.exists() and "PYTEST_CURRENT_TEST" not in os.environ:
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            if line.startswith(f"{name}="):
                return line.split("=", 1)[1].strip()
    if not generate:
        return ""
    value = Fernet.generate_key().decode()
    if "PYTEST_CURRENT_TEST" in os.environ:
        os.environ[name] = value
    else:
        with ENV_FILE.open("a", encoding="utf-8") as f:
            f.write(f"\n# Generated by the doctor module. Keep private; losing it makes stored records unreadable.\n{name}={value}\n")
    return value


def _fernet() -> Fernet:
    return Fernet(env_value("RECORDS_KEY", generate=True).encode())


def seal(obj) -> str:
    return _fernet().encrypt(json.dumps(obj, ensure_ascii=False).encode()).decode()


def unseal(token: str):
    return json.loads(_fernet().decrypt(token.encode()))


def db_path() -> Path:
    return Path(os.environ.get("CURANEX_DB", str(DB)))


def connect() -> sqlite3.Connection:
    path = db_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(path, check_same_thread=False)
    con.row_factory = sqlite3.Row
    con.executescript("""
    CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY, email TEXT UNIQUE NOT NULL, name TEXT, role TEXT NOT NULL,
        status TEXT NOT NULL, details TEXT, salt TEXT NOT NULL, pw_hash TEXT NOT NULL, created REAL NOT NULL);
    CREATE TABLE IF NOT EXISTS tokens (token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL, expires REAL NOT NULL);
    CREATE TABLE IF NOT EXISTS cases (id INTEGER PRIMARY KEY, patient_id INTEGER NOT NULL, title TEXT, data TEXT NOT NULL, created REAL NOT NULL);
    CREATE TABLE IF NOT EXISTS shares (case_id INTEGER NOT NULL, doctor_id INTEGER NOT NULL, granted REAL NOT NULL, revoked REAL,
        PRIMARY KEY (case_id, doctor_id));
    CREATE TABLE IF NOT EXISTS plans (id INTEGER PRIMARY KEY, case_id INTEGER NOT NULL, doctor_id INTEGER NOT NULL, data TEXT NOT NULL,
        confirmed REAL NOT NULL);
    CREATE TABLE IF NOT EXISTS audit (id INTEGER PRIMARY KEY, user_id INTEGER, action TEXT NOT NULL, case_id INTEGER, at REAL NOT NULL);
    """)
    return con


def hash_password(password: str, salt: str) -> str:
    return hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=2**14, r=8, p=1).hex()


def audit(con: sqlite3.Connection, user_id: int | None, action: str, case_id: int | None = None) -> None:
    con.execute("INSERT INTO audit (user_id, action, case_id, at) VALUES (?, ?, ?, ?)", (user_id, action, case_id, time.time()))


def create_user(email: str, password: str, name: str, role: str, details: dict | None = None) -> dict:
    email = email.strip().lower()
    admin_email = env_value("ADMIN_EMAIL").strip().lower()
    if admin_email and email == admin_email:
        role, status = "admin", "approved"
    else:
        status = "pending" if role == "doctor" else "approved"
    salt = secrets.token_hex(16)
    with _lock:
        con = connect()
        try:
            cur = con.execute("INSERT INTO users (email, name, role, status, details, salt, pw_hash, created) VALUES (?,?,?,?,?,?,?,?)",
                              (email, name, role, status, json.dumps(details or {}), salt, hash_password(password, salt), time.time()))
        except sqlite3.IntegrityError:
            con.close()
            raise ValueError("An account with this email already exists.") from None
        audit(con, cur.lastrowid, f"signup:{role}")
        con.commit()
        user = dict(con.execute("SELECT * FROM users WHERE id = ?", (cur.lastrowid,)).fetchone())
        con.close()
    return public(user)


def public(user: dict) -> dict:
    return {k: user[k] for k in ("id", "email", "name", "role", "status")} | {"details": json.loads(user.get("details") or "{}")}


def login(email: str, password: str) -> tuple[str, dict] | None:
    with _lock:
        con = connect()
        row = con.execute("SELECT * FROM users WHERE email = ?", (email.strip().lower(),)).fetchone()
        if not row or not hmac.compare_digest(hash_password(password, row["salt"]), row["pw_hash"]):
            con.close()
            return None
        token = secrets.token_urlsafe(32)
        con.execute("INSERT INTO tokens VALUES (?, ?, ?)", (hashlib.sha256(token.encode()).hexdigest(), row["id"], time.time() + TOKEN_TTL_S))
        audit(con, row["id"], "login")
        con.commit()
        con.close()
    return token, public(dict(row))


def user_for_token(token: str) -> dict | None:
    with _lock:
        con = connect()
        row = con.execute("SELECT u.* FROM tokens t JOIN users u ON u.id = t.user_id WHERE t.token_hash = ? AND t.expires > ?",
                          (hashlib.sha256(token.encode()).hexdigest(), time.time())).fetchone()
        con.close()
    return public(dict(row)) if row else None


def logout(token: str) -> None:
    with _lock:
        con = connect()
        con.execute("DELETE FROM tokens WHERE token_hash = ?", (hashlib.sha256(token.encode()).hexdigest(),))
        con.commit()
        con.close()
